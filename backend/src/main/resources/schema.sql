-- =====================================================================
-- MODULE TRA CUU TOUR VA GOI Y TOUR THEO SO THICH
-- Schema cho H2 (MODE=PostgreSQL). Kieu du lieu theo dac ta ky thuat.
-- =====================================================================

DROP TABLE IF EXISTS departure_offer_versions;
DROP TABLE IF EXISTS tour_departures;
DROP TABLE IF EXISTS tour_media;
DROP TABLE IF EXISTS tour_version_interest_tags;
DROP TABLE IF EXISTS tour_interests;
DROP TABLE IF EXISTS tour_version_destinations;
DROP TABLE IF EXISTS tour_versions;
DROP TABLE IF EXISTS tours;
DROP TABLE IF EXISTS destinations;
DROP TABLE IF EXISTS app_users;

-- 4.0 Nguoi dung (phuc vu JWT cho cac API noi bo)
CREATE TABLE app_users (
    user_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(64)  NOT NULL UNIQUE,
    password_hash  VARCHAR(200) NOT NULL,
    full_name      VARCHAR(120) NOT NULL,
    role           VARCHAR(16)  NOT NULL,   -- CUSTOMER, PRODUCT, MANAGER, ADMIN
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER','PRODUCT','MANAGER','ADMIN'))
);

-- 4.3 Danh muc diem den
CREATE TABLE destinations (
    destination_id        VARCHAR(20)  PRIMARY KEY,
    name                  VARCHAR(120) NOT NULL,
    slug                  VARCHAR(180) NOT NULL UNIQUE,
    destination_type      VARCHAR(16)  NOT NULL,
    parent_destination_id VARCHAR(20),
    province_name         VARCHAR(120),
    region                VARCHAR(60),
    country_code          CHAR(2)      NOT NULL DEFAULT 'VN',
    latitude              NUMERIC(9,6),
    longitude             NUMERIC(9,6),
    is_active             BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dest_parent FOREIGN KEY (parent_destination_id) REFERENCES destinations(destination_id),
    CONSTRAINT ck_dest_type CHECK (destination_type IN ('CITY','PROVINCE','ATTRACTION','REGION')),
    CONSTRAINT ck_dest_lat  CHECK (latitude  IS NULL OR (latitude  BETWEEN -90  AND 90)),
    CONSTRAINT ck_dest_lng  CHECK (longitude IS NULL OR (longitude BETWEEN -180 AND 180)),
    -- Toa do phai luu theo cap
    CONSTRAINT ck_dest_coord_pair CHECK ((latitude IS NULL AND longitude IS NULL)
                                      OR (latitude IS NOT NULL AND longitude IS NOT NULL))
);

-- 4.1 Tour (dinh danh on dinh cua san pham Tour)
CREATE TABLE tours (
    tour_id                      BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_code                    VARCHAR(24) NOT NULL UNIQUE,
    slug                         VARCHAR(180) NOT NULL UNIQUE,
    lifecycle_status             VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    current_published_version_id BIGINT,
    created_by_user_id           BIGINT,
    updated_by_user_id           BIGINT,
    revision                     INTEGER     NOT NULL DEFAULT 0,
    created_at                   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_tours_lifecycle CHECK (lifecycle_status IN ('ACTIVE','ARCHIVED'))
);

-- 4.2 Phien ban noi dung Tour
CREATE TABLE tour_versions (
    tour_version_id        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id                BIGINT      NOT NULL,
    version_no             INTEGER     NOT NULL,
    content_status         VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    title                  VARCHAR(200) NOT NULL,
    summary                VARCHAR(500),
    description            TEXT,
    origin_destination_id  VARCHAR(20),
    duration_days          SMALLINT    NOT NULL,
    nights                 SMALLINT    NOT NULL DEFAULT 0,
    itinerary_json         TEXT,
    included_services_json TEXT,
    excluded_services_json TEXT,
    created_by_user_id     BIGINT,
    reviewed_by_user_id    BIGINT,
    reviewed_at            TIMESTAMP WITH TIME ZONE,
    published_at           TIMESTAMP WITH TIME ZONE,
    rejection_reason       TEXT,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tv_tour   FOREIGN KEY (tour_id) REFERENCES tours(tour_id),
    CONSTRAINT fk_tv_origin FOREIGN KEY (origin_destination_id) REFERENCES destinations(destination_id),
    CONSTRAINT uq_tv_tour_version UNIQUE (tour_id, version_no),
    CONSTRAINT ck_tv_status   CHECK (content_status IN ('DRAFT','PENDING','PUBLISHED','REJECTED')),
    CONSTRAINT ck_tv_duration CHECK (duration_days >= 1),
    CONSTRAINT ck_tv_nights   CHECK (nights >= 0 AND nights < duration_days)
);

ALTER TABLE tours ADD CONSTRAINT fk_tours_current_version
    FOREIGN KEY (current_published_version_id) REFERENCES tour_versions(tour_version_id);

-- 4.4 Diem den cua phien ban Tour
CREATE TABLE tour_version_destinations (
    tour_version_id BIGINT      NOT NULL,
    destination_id  VARCHAR(20) NOT NULL,
    stop_order      SMALLINT    NOT NULL DEFAULT 1,
    is_primary      BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tour_version_id, destination_id),
    CONSTRAINT fk_tvd_version FOREIGN KEY (tour_version_id) REFERENCES tour_versions(tour_version_id),
    CONSTRAINT fk_tvd_dest    FOREIGN KEY (destination_id)  REFERENCES destinations(destination_id)
);

-- 4.5 Danh muc so thich
CREATE TABLE tour_interests (
    interest_id   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(40)  NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    description   TEXT,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order SMALLINT     NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4.6 Gan so thich cho phien ban Tour (bang trung gian cua thuat toan)
CREATE TABLE tour_version_interest_tags (
    tour_version_id      BIGINT NOT NULL,
    interest_id          BIGINT NOT NULL,
    assigned_by_user_id  BIGINT,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tour_version_id, interest_id),
    CONSTRAINT fk_tag_version  FOREIGN KEY (tour_version_id) REFERENCES tour_versions(tour_version_id),
    CONSTRAINT fk_tag_interest FOREIGN KEY (interest_id)     REFERENCES tour_interests(interest_id)
);

-- 4.7 Hinh anh Tour
CREATE TABLE tour_media (
    media_id        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_version_id BIGINT      NOT NULL,
    media_type      VARCHAR(12) NOT NULL DEFAULT 'IMAGE',
    media_url       TEXT        NOT NULL,
    alt_text        VARCHAR(200),
    caption         VARCHAR(200),
    sort_order      SMALLINT    NOT NULL DEFAULT 0,
    is_cover        BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_media_version FOREIGN KEY (tour_version_id) REFERENCES tour_versions(tour_version_id)
);
-- Toi da MOT anh cover moi phien ban.
-- Tren PostgreSQL dung partial unique index:
--   CREATE UNIQUE INDEX uq_media_one_cover ON tour_media(tour_version_id) WHERE is_cover = TRUE;
-- H2 khong ho tro filtered index, nen rang buoc nay duoc kiem tra o tang Service.
CREATE INDEX ix_media_version ON tour_media(tour_version_id, is_cover);

-- 4.8 Chuyen khoi hanh
CREATE TABLE tour_departures (
    departure_id       BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_code     VARCHAR(28) NOT NULL UNIQUE,
    tour_id            BIGINT      NOT NULL,
    tour_version_id    BIGINT      NOT NULL,
    starts_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    booking_opens_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    booking_closes_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    sales_status       VARCHAR(16) NOT NULL DEFAULT 'CLOSED',
    total_seats        INTEGER     NOT NULL,
    sellable_capacity  INTEGER     NOT NULL,
    available_seats    INTEGER     NOT NULL DEFAULT 0,
    hold_seats         INTEGER     NOT NULL DEFAULT 0,
    confirmed_seats    INTEGER     NOT NULL DEFAULT 0,
    active_offer_id    BIGINT,
    revision           INTEGER     NOT NULL DEFAULT 0,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dep_tour    FOREIGN KEY (tour_id)         REFERENCES tours(tour_id),
    CONSTRAINT fk_dep_version FOREIGN KEY (tour_version_id) REFERENCES tour_versions(tour_version_id),
    CONSTRAINT ck_dep_status  CHECK (sales_status IN ('CLOSED','OPEN','CANCELLED','COMPLETED')),
    CONSTRAINT ck_dep_window  CHECK (booking_opens_at < booking_closes_at),
    CONSTRAINT ck_dep_time    CHECK (starts_at < ends_at),
    CONSTRAINT ck_dep_seats   CHECK (available_seats >= 0 AND sellable_capacity <= total_seats)
);

-- 4.9 Phien ban gia Tour
CREATE TABLE departure_offer_versions (
    offer_id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id        BIGINT       NOT NULL,
    version_no          INTEGER      NOT NULL,
    approval_status     VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    adult_price         NUMERIC(14,0) NOT NULL,
    child_price         NUMERIC(14,0),
    infant_price        NUMERIC(14,0),
    currency            CHAR(3)      NOT NULL DEFAULT 'VND',
    policy_json         TEXT,
    created_by_user_id  BIGINT,
    approved_by_user_id BIGINT,
    approved_at         TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_offer_dep FOREIGN KEY (departure_id) REFERENCES tour_departures(departure_id),
    CONSTRAINT uq_offer_version UNIQUE (departure_id, version_no),
    CONSTRAINT ck_offer_status CHECK (approval_status IN ('DRAFT','PENDING','APPROVED','REJECTED')),
    CONSTRAINT ck_offer_price  CHECK (adult_price >= 0)
);

ALTER TABLE tour_departures ADD CONSTRAINT fk_dep_active_offer
    FOREIGN KEY (active_offer_id) REFERENCES departure_offer_versions(offer_id);

-- Chi muc ho tro truy van tim kiem
CREATE INDEX ix_tv_tour_status  ON tour_versions(tour_id, content_status);
CREATE INDEX ix_tvd_dest        ON tour_version_destinations(destination_id);
CREATE INDEX ix_tag_interest    ON tour_version_interest_tags(interest_id);
CREATE INDEX ix_dep_tour_status ON tour_departures(tour_id, sales_status);
CREATE INDEX ix_offer_dep       ON departure_offer_versions(departure_id, approval_status);
